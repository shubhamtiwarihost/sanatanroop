// Usage: npm run admin:set-password -- <email> <password>
// Writes the admin credential hash used by src/lib/adminAuth.ts
import { pbkdf2Sync } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const [email, password] = process.argv.slice(2);
if (!email || !password) {
  console.error('Usage: npm run admin:set-password -- <email> <password>');
  process.exit(1);
}

// Must match src/lib/adminAuth.ts
const hash = pbkdf2Sync(password, 'sanatanroop-admin:' + email.trim().toLowerCase(), 310000, 32, 'sha256').toString('hex');

writeFileSync(
  new URL('../src/config/adminCredentials.ts', import.meta.url),
  `// Generated by scripts/set-admin-password.mjs — do not edit by hand\nexport const ADMIN_CREDENTIAL_HASH = '${hash}';\n`
);
console.log('Admin credentials updated. Commit src/config/adminCredentials.ts and deploy.');
